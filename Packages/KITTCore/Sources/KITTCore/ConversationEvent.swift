import Foundation

/// Identifies the device that created an event ("watch-<uuid>", "mac-<uuid>").
public struct DeviceID: Hashable, Codable, Sendable, CustomStringConvertible {
    public let raw: String
    public init(_ raw: String) { self.raw = raw }
    public var description: String { raw }
}

/// One saved fact in a conversation. Matches the brief's replication record so the
/// later watch→Mac handoff can ship these unchanged:
/// event ID, conversation ID, parent event ID, originating device, local sequence,
/// timestamp, type, payload. Ordering comes from parent links and per-device sequence,
/// never from the timestamp alone.
public struct ConversationEvent: Codable, Equatable, Identifiable, Sendable {
    public var id: UUID
    public var conversationID: UUID
    public var parentID: UUID?
    public var device: DeviceID
    public var localSequence: Int64
    public var timestamp: Date
    public var type: EventType
    public var payload: EventPayload

    public init(id: UUID = UUID(), conversationID: UUID, parentID: UUID?, device: DeviceID,
                localSequence: Int64, timestamp: Date = Date(), payload: EventPayload) {
        self.id = id
        self.conversationID = conversationID
        self.parentID = parentID
        self.device = device
        self.localSequence = localSequence
        self.timestamp = timestamp
        self.type = payload.type
        self.payload = payload
    }
}

public enum EventType: String, Codable, Sendable {
    case userMessage
    case assistantMessage
    case householdFact
    case calculation
    case condition
    case waterNotice
}

public enum EventPayload: Codable, Equatable, Sendable {
    /// Exact user wording, never normalized.
    case userMessage(text: String, inputMethod: InputMethod)
    case assistantMessage(AssistantMessage)
    case householdFact(HouseholdFact)
    case calculation(WaterCalculation)
    /// A hazard was raised or cleared in this conversation.
    case condition(ConditionChange)
    /// A water notice was reported, left unknown, or lifted in this conversation.
    case waterNotice(WaterNoticeChange)

    public var type: EventType {
        switch self {
        case .userMessage: return .userMessage
        case .assistantMessage: return .assistantMessage
        case .householdFact: return .householdFact
        case .calculation: return .calculation
        case .condition: return .condition
        case .waterNotice: return .waterNotice
        }
    }
}

public enum InputMethod: String, Codable, Sendable {
    case typed, dictated, suggestion, unknown
}

public struct AssistantMessage: Codable, Equatable, Sendable {
    public enum Origin: String, Codable, Sendable {
        /// Reviewed guide text shown verbatim (plus app arithmetic).
        case guide
        /// The app itself: a question for one missing fact, a confirmation, or
        /// "the guide doesn't cover that".
        case app
        /// Generated by the local model.
        case model
    }
    public var text: String
    public var origin: Origin
    /// "entryID@vN" for every guide entry used. For a model reply these are the entries
    /// whose passages were in the prompt; an empty list means the reply had no guide text
    /// behind it at all.
    public var citations: [String]
    /// Model file name + checksum prefix when origin == .model.
    public var modelID: String?
    /// True if generation stopped early (app closed, wrist lowered, out of context).
    public var interrupted: Bool
    /// Guide entries offered as buttons under this message.
    public var suggestions: [String]
    /// The guide had no reliable answer; the UI may offer an unverified model reply.
    public var offersModel: Bool
    /// The one household fact KITT needs before it can answer.
    public var needsFact: HouseholdFact.Key?
    /// Numbers in a model reply that appear nowhere in the guide text it was given.
    /// The UI shows a caution when this is not empty.
    public var unsupportedNumbers: [String]
    /// A hazard entry shown as a precaution because the question might involve it. It is
    /// not flagged: the UI offers "This applies to us", which flags it.
    public var suggestedHazard: String?
    /// The reply ended with the hazard's question ("Is it running there...?"). A yes to it
    /// flags `suggestedHazard`.
    public var asksHazardQuestion: Bool
    /// The reply asked which water notice it is ("What does the notice say?"). This is the
    /// user's question it answers once told.
    public var noticeQuestion: String?

    public init(text: String, origin: Origin, citations: [String] = [], modelID: String? = nil, interrupted: Bool = false,
                suggestions: [String] = [], offersModel: Bool = false, needsFact: HouseholdFact.Key? = nil,
                unsupportedNumbers: [String] = [], suggestedHazard: String? = nil, asksHazardQuestion: Bool = false,
                noticeQuestion: String? = nil) {
        self.text = text
        self.origin = origin
        self.citations = citations
        self.modelID = modelID
        self.interrupted = interrupted
        self.suggestions = suggestions
        self.offersModel = offersModel
        self.needsFact = needsFact
        self.unsupportedNumbers = unsupportedNumbers
        self.suggestedHazard = suggestedHazard
        self.asksHazardQuestion = asksHazardQuestion
        self.noticeQuestion = noticeQuestion
    }

    enum CodingKeys: String, CodingKey {
        case text, origin, citations, modelID, interrupted, suggestions, offersModel, needsFact, unsupportedNumbers, suggestedHazard, asksHazardQuestion
        case noticeQuestion
    }

    /// The one fact this reply asks the user for, if any: "notice" (which water notice),
    /// "hazardUse" (the hazard's question), or a household fact ("people", "planDays",
    /// "storedWater").
    public var askedFor: String? {
        if noticeQuestion != nil { return "notice" }
        if asksHazardQuestion { return "hazardUse" }
        return needsFact?.rawValue
    }

    // Fields added after the first build decode as their defaults, so an older peer's
    // events stay readable.
    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        text = try c.decode(String.self, forKey: .text)
        origin = try c.decode(Origin.self, forKey: .origin)
        citations = try c.decodeIfPresent([String].self, forKey: .citations) ?? []
        modelID = try c.decodeIfPresent(String.self, forKey: .modelID)
        interrupted = try c.decodeIfPresent(Bool.self, forKey: .interrupted) ?? false
        suggestions = try c.decodeIfPresent([String].self, forKey: .suggestions) ?? []
        offersModel = try c.decodeIfPresent(Bool.self, forKey: .offersModel) ?? false
        needsFact = try c.decodeIfPresent(HouseholdFact.Key.self, forKey: .needsFact)
        unsupportedNumbers = try c.decodeIfPresent([String].self, forKey: .unsupportedNumbers) ?? []
        suggestedHazard = try c.decodeIfPresent(String.self, forKey: .suggestedHazard)
        asksHazardQuestion = try c.decodeIfPresent(Bool.self, forKey: .asksHazardQuestion) ?? false
        noticeQuestion = try c.decodeIfPresent(String.self, forKey: .noticeQuestion)
    }
}

/// A hazard entry becoming active or being cleared. Saved as its own event so the Mac
/// sees the condition itself, not just the sentence that caused it.
public struct ConditionChange: Codable, Equatable, Sendable {
    public enum State: String, Codable, Sendable {
        case raised, cleared
        /// Answer to the hazard's question: not in use, or not this hazard. Not flagged.
        case ruledOut
        /// Answer to the hazard's question: the user does not know yet. Not flagged, and the
        /// question stays open.
        case unknown

        /// How a transcript names this change. "Not in use" and "Not sure" stay apart so a
        /// helper reading the handoff knows whether use was ruled out or is still unknown.
        public var title: String {
            switch self {
            case .raised: return "Flagged"
            case .cleared: return "Cleared"
            case .ruledOut: return "Not in use"
            case .unknown: return "Not sure"
            }
        }
    }
    /// Why a hazard was flagged. A flag changes how every later turn is answered, so it
    /// is only set on something the user said or did, never on KITT's guess alone.
    public enum Basis: String, Codable, Sendable {
        /// The message described the hazard ("our water smells like gasoline").
        case described
        /// KITT showed the warning as a precaution and the user tapped "This applies to us".
        case confirmed
        /// KITT showed the warning as a precaution and the next message, read with the one
        /// before, described the risky use ("can I run it in the basement?").
        case followUp
        /// KITT asked its question ("Is it running there...?") and the user said yes.
        case answered
    }
    /// Guide entry that defines the hazard.
    public var entryID: String
    public var state: State
    /// The user words that raised it, if any.
    public var sourceText: String?
    /// Set for `.raised`. Missing in events written before this field existed.
    public var basis: Basis?

    public init(entryID: String, state: State, sourceText: String? = nil, basis: Basis? = nil) {
        self.entryID = entryID
        self.state = state
        self.sourceText = sourceText
        self.basis = basis
    }
}

/// A household fact, kept apart from published guidance.
public struct HouseholdFact: Codable, Equatable, Sendable {
    public enum Key: String, Codable, Sendable, CaseIterable {
        case people          // value: count of people
        case storedWater     // value: US gallons on hand
        case planDays        // value: days the plan should cover
    }
    public var key: Key
    public var value: Double
    /// The user words that set it, if any (kept for "why do you think we have 4 gallons?").
    public var sourceText: String?

    public init(key: Key, value: Double, sourceText: String? = nil) {
        self.key = key
        self.value = value
        self.sourceText = sourceText
    }
}

/// The inputs and result of one water calculation, with units in the field names.
public struct WaterCalculation: Codable, Equatable, Sendable {
    public var people: Int
    public var days: Int
    public var gallonsPerPersonDay: Double
    public var requiredGallons: Double
    public var storedGallons: Double?
    public var shortfallGallons: Double?
    public var guideCitation: String

    public init(plan: WaterPlan, guideCitation: String) {
        people = plan.people.count
        days = plan.days.count
        gallonsPerPersonDay = plan.rate.value
        requiredGallons = plan.required.value
        storedGallons = plan.stored?.value
        shortfallGallons = plan.shortfall?.value
        self.guideCitation = guideCitation
    }
}
